const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=__dirname,dist=root;
const read=name=>fs.readFileSync(path.join(dist,name),'utf8');
const catalog=read('catalog.js'),app=read('app.js'),friend=read('friend.js');
new vm.Script(catalog);new vm.Script(app);new vm.Script(friend);
const context={window:{}};vm.runInNewContext(catalog,context);
const books=context.window.FRIENDLY_BOOKS;
const assert=(pass,message)=>{if(!pass)throw Error(message);};
assert(books.length===9,'Expected all nine books.');
assert(new Set(books.map(b=>b.id)).size===9,'Duplicate book ID.');
assert(new Set(books.map(b=>b.url)).size===9,'Duplicate book destination.');
const find=id=>books.find(b=>b.id===id);
assert(find('rex').categories.includes('animals')&&find('rex').categories.includes('stories'),'Rex and Billy must appear in both categories.');
assert(find('usa').categories.includes('community')&&find('usa').categories.includes('explore'),'Travel the USA must appear in both categories.');
assert(['scifi','fantasy'].every(id=>find(id).categories.includes('explore')),'Both imaginative adventures must be in Explore.');
let html=fs.readFileSync(path.join(root,'page.html'),'utf8');
assert(!html.includes('Where shall we go?')&&!html.includes('id="worlds"'),'Removed destination section remains.');
assert(html.includes('data-place="university"')&&html.includes('data-place="duckies"'),'Missing RoboTown discoveries.');
assert(html.includes('the tomorrow-ers')&&html.includes('nieces and nephews'),'Missing author story or dedication.');
assert(!/gumroad|id="printables"|href="#printables"/.test(html),'Print and Play must remain disabled.');
assert(['id="friend"','id="hero-friend"','id="friend-line"','id="maker-robot"','id="print-sheet"'].every(id=>html.includes(id)),'Missing robot friend maker.');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
for(const m of html.matchAll(/href="#([^"]+)"/g))assert(ids.includes(m[1]),'Missing anchor: '+m[1]);
for(const m of html.matchAll(/data-book="([^"]+)"/g))assert(find(m[1]),'Unknown book pin.');
let css=read('styles.css');
const jpg=fs.readFileSync(path.join(dist,'assets','robotown.jpg'));
css=css.replace("url('assets/robotown.jpg')","url('data:image/jpeg;base64,"+jpg.toString('base64')+"')");
html=html.replace('<link rel="stylesheet" href="styles.css">','<style>'+css+'</style>');
html=html.replace('<script src="catalog.js"></script><script src="app.js"></script><script src="friend.js"></script>',()=>'<script>'+catalog+'</script><script>'+app+'</script><script>'+friend+'</script>');
assert(!html.includes('src="friend.js"'),'Robot friend script was not embedded.');
assert(html.includes('data:image/jpeg;base64,'),'Missing embedded RoboTown illustration.');
fs.writeFileSync(path.join(dist,'index.html'),html,'utf8');
console.log('Built the single-file RoboTown homepage ('+Math.round(Buffer.byteLength(html)/1024)+' KB).');
console.log('Passed: JavaScript syntax, all nine books, requested overlapping categories, image embedding, section links, lore discoveries, dedication, robot friend maker, and disabled Print & Play.');

